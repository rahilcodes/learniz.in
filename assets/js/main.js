  // Interactive FAQ Accordion & Search Filter
  // =========================================================================
  function initFAQAccordion() {
    const faqButtons = document.querySelectorAll('.lz-faq-btn');
    faqButtons.forEach(btn => {
      btn.addEventListener('click', function () {
        const item = btn.closest('.lz-faq-item');
        const isOpen = btn.getAttribute('aria-expanded') === 'true';

        // Close other items in the same container
        const parent = item.parentElement;
        parent.querySelectorAll('.lz-faq-item').forEach(other => {
          if (other !== item) {
            other.classList.remove('active');
            const otherBtn = other.querySelector('.lz-faq-btn');
            if (otherBtn) otherBtn.setAttribute('aria-expanded', 'false');
          }
        });

        // Toggle current item
        if (isOpen) {
          item.classList.remove('active');
          btn.setAttribute('aria-expanded', 'false');
        } else {
          item.classList.add('active');
          btn.setAttribute('aria-expanded', 'true');
        }
      });
    });

    // Search and Category filtering on FAQ page
    const faqSearch = document.getElementById('faq-search-input');
    const categoryTabs = document.querySelectorAll('[data-faq-cat]');
    const faqItems = document.querySelectorAll('.lz-faq-item[data-cat]');

    function filterFaqs() {
      const query = faqSearch ? faqSearch.value.toLowerCase().trim() : '';
      const activeTab = document.querySelector('[data-faq-cat].active');
      const category = activeTab ? activeTab.getAttribute('data-faq-cat') : 'all';

      faqItems.forEach(item => {
        const itemCat = item.getAttribute('data-cat');
        const text = item.textContent.toLowerCase();
        const matchesCat = category === 'all' || itemCat === category;
        const matchesQuery = !query || text.includes(query);

        if (matchesCat && matchesQuery) {
          item.style.display = '';
        } else {
          item.style.display = 'none';
        }
      });
    }

    if (faqSearch) {
      faqSearch.addEventListener('input', filterFaqs);
    }

    categoryTabs.forEach(tab => {
      tab.addEventListener('click', function () {
        categoryTabs.forEach(t => t.classList.remove('active'));
        tab.classList.add('active');
        filterFaqs();
      });
    });
  }

