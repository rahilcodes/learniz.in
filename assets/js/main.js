  // =========================================================================
  // Interactive Demo Booking Modal
  // =========================================================================
  function initDemoModal() {
    const modalBackdrop = document.getElementById('lz-demo-modal');
    if (!modalBackdrop) return;

    const closeBtn = document.getElementById('lz-modal-close');
    const form = document.getElementById('lz-demo-form');
    const successView = document.getElementById('lz-demo-success');
    const formView = document.getElementById('lz-demo-form-view');
    const successName = document.getElementById('lz-success-name');
    const successPhone = document.getElementById('lz-success-phone');

    function openModal() {
      modalBackdrop.classList.add('open');
      document.body.style.overflow = 'hidden';
      if (formView && successView) {
        formView.style.display = 'grid';
        successView.style.display = 'none';
      }
    }

    function closeModal() {
      modalBackdrop.classList.remove('open');
      document.body.style.overflow = '';
    }

    window.addEventListener('learniz:book-demo', openModal);

    if (closeBtn) {
      closeBtn.addEventListener('click', closeModal);
    }

    modalBackdrop.addEventListener('click', function (e) {
      if (e.target === modalBackdrop) {
        closeModal();
      }
    });

    window.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && modalBackdrop.classList.contains('open')) {
        closeModal();
      }
    });

    // Form validation and submission
    if (form) {
      form.addEventListener('submit', function (e) {
        e.preventDefault();
        let hasErrors = false;

        const nameInput = form.querySelector('[name="name"]');
        const schoolInput = form.querySelector('[name="school"]');
        const cityInput = form.querySelector('[name="city"]');
        const roleInput = form.querySelector('[name="role"]');
        const phoneInput = form.querySelector('[name="phone"]');

        const nameErr = document.getElementById('err-name');
        const schoolErr = document.getElementById('err-school');
        const cityErr = document.getElementById('err-city');
        const roleErr = document.getElementById('err-role');
        const phoneErr = document.getElementById('err-phone');

        // Reset errors
        [nameErr, schoolErr, cityErr, roleErr, phoneErr].forEach(el => { if (el) el.textContent = ''; });
        form.querySelectorAll('.lz-input, .lz-select').forEach(el => el.removeAttribute('aria-invalid'));

        if (!nameInput.value.trim()) {
          nameErr.textContent = 'Please enter your name.';
          nameInput.setAttribute('aria-invalid', 'true');
          hasErrors = true;
        }

        if (!schoolInput.value.trim()) {
          schoolErr.textContent = 'Please enter your school or institution.';
          schoolInput.setAttribute('aria-invalid', 'true');
          hasErrors = true;
        }

        if (!cityInput.value.trim()) {
          cityErr.textContent = 'Please enter your city.';
          cityInput.setAttribute('aria-invalid', 'true');
          hasErrors = true;
        }

        if (!roleInput.value) {
          roleErr.textContent = 'Please select your role.';
          roleInput.setAttribute('aria-invalid', 'true');
          hasErrors = true;
        }

        const digits = phoneInput.value.replace(/\D/g, '');
        if (!digits) {
          phoneErr.textContent = 'Please enter a mobile number.';
          phoneInput.setAttribute('aria-invalid', 'true');
          hasErrors = true;
        } else if (!/^(91)?[6-9]\d{9}$/.test(digits)) {
          phoneErr.textContent = 'Enter a valid 10-digit Indian mobile number.';
          phoneInput.setAttribute('aria-invalid', 'true');
          hasErrors = true;
        }

        if (hasErrors) return;

        // Submitting state
        const submitBtn = form.querySelector('button[type="submit"]');
        const originalText = submitBtn.innerHTML;
        submitBtn.disabled = true;
        submitBtn.innerHTML = '<span class="lz-spinner"></span> Requesting slot…';

        setTimeout(function () {
          submitBtn.disabled = false;
          submitBtn.innerHTML = originalText;
          if (formView && successView) {
            formView.style.display = 'none';
            successView.style.display = 'grid';
            if (successName) {
              const firstName = nameInput.value.trim().split(' ')[0] || 'there';
              successName.textContent = firstName;
            }
            if (successPhone) {
              successPhone.textContent = phoneInput.value.trim();
            }
          }
          form.reset();
        }, 900);
      });
    }

    // Success close button
    const successCloseBtn = document.getElementById('lz-success-close');
    if (successCloseBtn) {
      successCloseBtn.addEventListener('click', closeModal);
    }
  }

  // =========================================================================
  // Interactive Helicopter Physics Simulator
  // =========================================================================
  function initHelicopterSim() {
    const rpmSlider = document.getElementById('sim-rpm');
    const massSlider = document.getElementById('sim-mass');
    if (!rpmSlider || !massSlider) return;

    const rpmLabel = document.getElementById('sim-rpm-val');
    const massLabel = document.getElementById('sim-mass-val');
    const liftKN = document.getElementById('sim-lift-kn');
    const weightKN = document.getElementById('sim-weight-kn');
    const statusBadge = document.getElementById('sim-status');
    const heliCraft = document.getElementById('sim-craft');
    const rotorBlade = document.getElementById('sim-rotor');
    const liftVector = document.getElementById('sim-arrow-lift');
    const weightVector = document.getElementById('sim-arrow-weight');
    const resetBtn = document.getElementById('sim-reset');

    function updateSimulation() {
      const rpm = Number(rpmSlider.value);
      const mass = Number(massSlider.value);

      if (rpmLabel) rpmLabel.textContent = rpm + ' rpm';
      if (massLabel) massLabel.textContent = mass.toLocaleString('en-IN') + ' kg';

      // Physics model: weight = m * g, lift = 0.0736 * rpm^2
      const weight = mass * 9.81;
      const lift = 0.0736 * rpm * rpm;
      const ratio = lift / weight;

      if (liftKN) liftKN.textContent = 'Lift ' + (lift / 1000).toFixed(1) + ' kN';
      if (weightKN) weightKN.textContent = 'Weight ' + (weight / 1000).toFixed(1) + ' kN';

      // Status calculation
      let statusText = 'Hovering';
      let statusBg = '#EEF4FF';
      let statusFg = 'hsl(217, 91%, 40%)';

      if (ratio > 1.03) {
        statusText = 'Climbing';
        statusBg = '#E8F7EE';
        statusFg = '#15803D';
      } else if (ratio < 0.97) {
        statusText = 'Descending';
        statusBg = '#FFF1E8';
        statusFg = 'hsl(25, 95%, 40%)';
      }

      if (statusBadge) {
        statusBadge.textContent = statusText;
        statusBadge.style.backgroundColor = statusBg;
        statusBadge.style.color = statusFg;
      }

      // Altitude animation
      const alt = Math.max(0, Math.min(100, ((ratio - 0.8) / 0.5) * 100));
      const bottomPct = (14 + alt * 0.36) + '%';
      if (heliCraft) {
        heliCraft.style.bottom = bottomPct;
      }

      // Rotor animation duration
      const rotorDur = (0.5 - (rpm - 250) / 350 * 0.38).toFixed(2) + 's';
      if (rotorBlade) {
        rotorBlade.style.animationDuration = rotorDur;
      }

      // Vector arrows
      const liftHeight = Math.round(20 + Math.min(1.6, ratio) * 30) + 'px';
      const weightHeight = Math.round(20 + (mass / 1600) * 40) + 'px';
      if (liftVector) liftVector.style.height = liftHeight;
      if (weightVector) weightVector.style.height = weightHeight;
    }

    rpmSlider.addEventListener('input', updateSimulation);
    massSlider.addEventListener('input', updateSimulation);

    if (resetBtn) {
      resetBtn.addEventListener('click', function () {
        rpmSlider.value = 400;
        massSlider.value = 1200;
        updateSimulation();
      });
    }

    // Initial run
    updateSimulation();
  }

