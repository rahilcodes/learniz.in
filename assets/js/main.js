  function initIntelliQ() {
    const subjectSelect = document.getElementById('iq-subject');
    const topicInput = document.getElementById('iq-topic');
    const typeSelect = document.getElementById('iq-type');
    const countDisplay = document.getElementById('iq-count-val');
    const incBtn = document.getElementById('iq-count-inc');
    const decBtn = document.getElementById('iq-count-dec');
    const generateBtn = document.getElementById('iq-generate-btn');
    const diffButtons = document.querySelectorAll('[data-iq-diff]');
    const resultsContainer = document.getElementById('iq-results');
    const summaryLabel = document.getElementById('iq-summary');

    if (!generateBtn || !resultsContainer) return;

    let selectedDiff = 'Medium';
    let count = 5;

    // Difficulty buttons
    diffButtons.forEach(btn => {
      btn.addEventListener('click', function () {
        diffButtons.forEach(b => {
          b.style.background = 'transparent';
          b.style.color = '#5B6678';
          b.style.boxShadow = 'none';
        });
        btn.style.background = '#fff';
        btn.style.color = '#0B1324';
        btn.style.boxShadow = '0 1px 3px rgba(11,19,36,.12)';
        selectedDiff = btn.getAttribute('data-iq-diff');
      });
    });

    // Count steppers
    if (incBtn && countDisplay) {
      incBtn.addEventListener('click', function () {
        if (count < 20) {
          count++;
          countDisplay.textContent = count;
        }
      });
    }

    if (decBtn && countDisplay) {
      decBtn.addEventListener('click', function () {
        if (count > 3) {
          count--;
          countDisplay.textContent = count;
        }
      });
    }

    function renderQuestions() {
      const subject = subjectSelect ? subjectSelect.value : 'Biology';
      const topic = topicInput ? topicInput.value : 'Photosynthesis';
      const type = typeSelect ? typeSelect.value : 'mcq';

      // Pick questions or fallback
      let qList = [];
      if (iqDatabases[subject] && iqDatabases[subject][topic] && iqDatabases[subject][topic][type]) {
        qList = iqDatabases[subject][topic][type];
      } else if (iqDatabases[subject]) {
        const firstTopic = Object.keys(iqDatabases[subject])[0];
        qList = iqDatabases[subject][firstTopic][type] || iqDatabases.Biology.Photosynthesis[type];
      } else {
        qList = iqDatabases.Biology.Photosynthesis[type];
      }

      const typeLabel = { mcq: 'multiple-choice', short: 'short-answer', fill: 'fill-in-the-blank' }[type] || 'questions';
      if (summaryLabel) {
        summaryLabel.textContent = `Showing ${Math.min(3, qList.length)} of ${count} ${typeLabel} questions · ${subject} · ${topic}`;
      }

      let html = '';
      qList.slice(0, 3).forEach((q, idx) => {
        const numStr = String(idx + 1).padStart(2, '0');
        let optionsHtml = '';
        if (q.opts && q.opts.length) {
          optionsHtml = `<div class="lz-iq-options-grid">
            ${q.opts.map((opt, j) => {
              const isCorrect = j === q.ans;
              const border = isCorrect ? '#BBE5C8' : '#E5E8EF';
              const bg = isCorrect ? '#F2FBF5' : '#fff';
              const badgeBg = isCorrect ? '#15803D' : '#EEF0F4';
              const badgeFg = isCorrect ? '#fff' : '#3F4A5C';
              const label = 'ABCD'[j];
              return `<span style="display:flex;gap:8px;align-items:center;padding:7px 10px;border-radius:8px;border:1px solid ${border};background:${bg};font-size:13.5px;color:#1F2A3D">
                <span style="width:20px;height:20px;border-radius:6px;display:grid;place-items:center;font-size:11px;font-weight:700;background:${badgeBg};color:${badgeFg};flex:none">${label}</span>
                ${opt}
              </span>`;
            }).join('')}
          </div>`;
        }

        html += `<article style="border:1px solid #E5E8EF;border-radius:12px;padding:14px 16px;display:grid;gap:10px;background:#fff">
          <div style="display:flex;gap:12px;align-items:flex-start">
            <span style="font-family:ui-monospace,SFMono-Regular,monospace;font-size:12px;color:#98A1B2;padding-top:3px">${numStr}</span>
            <p style="font-size:15px;line-height:1.5;color:#0B1324;font-weight:500;margin:0;flex:1">${q.text}</p>
          </div>
          ${optionsHtml}
          <div class="lz-iq-tags-row" style="display:flex;flex-wrap:wrap;gap:6px;padding-left:28px;align-items:center">
            <span style="padding:3px 8px;border-radius:6px;background:#F3EFFF;color:hsl(258 90% 48%);font-size:11.5px;font-weight:600">${topic}</span>
            <span style="padding:3px 8px;border-radius:6px;background:#F3F5F9;color:#3F4A5C;font-size:11.5px;font-weight:600">${selectedDiff}</span>
            ${q.meta ? `<span style="font-size:12.5px;color:#6B7485">${q.meta}</span>` : ''}
            <span style="margin-left:auto;font-size:12.5px;font-weight:600;color:hsl(217 91% 45%);cursor:pointer">Edit</span>
          </div>
        </article>`;
      });

      resultsContainer.innerHTML = html;
    }

    generateBtn.addEventListener('click', function () {
      generateBtn.disabled = true;
      generateBtn.innerHTML = '<span class="lz-spinner"></span> Drafting questions…';
      resultsContainer.style.opacity = '0.35';

      setTimeout(function () {
        generateBtn.disabled = false;
        generateBtn.innerHTML = 'Generate questions';
        resultsContainer.style.opacity = '1';
        renderQuestions();
      }, 700);
    });

    // When subject changes, suggest suitable topic
    if (subjectSelect && topicInput) {
      subjectSelect.addEventListener('change', function () {
        if (subjectSelect.value === 'Biology') topicInput.value = 'Photosynthesis';
        else if (subjectSelect.value === 'Physics') topicInput.value = 'Forces on a helicopter';
        else if (subjectSelect.value === 'Chemistry') topicInput.value = 'Chemical Bonding';
        else if (subjectSelect.value === 'Mathematics') topicInput.value = 'Quadratic Equations';
      });
    }
  }

